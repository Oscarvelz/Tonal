function tempOk(w: number, kind: TempKind): boolean {
  switch (kind) {
    case "warm":
      return w >= 0.25;
    case "cool":
      return w <= -0.2;
    case "warm-neutral":
      return w >= -0.05;
    case "cool-neutral":
      return w <= 0.05;
  }
}

const RELAX: Record<TempKind, TempKind> = {
  warm: "warm-neutral",
  cool: "cool-neutral",
  "warm-neutral": "warm-neutral",
  "cool-neutral": "cool-neutral",
};

const UND_SIGN: Record<string, number> = { warm: 0.6, cool: -0.6, neutral: 0 };
const UND_KINDS: Record<string, TempKind[]> = {
  warm: ["warm", "warm-neutral"],
  cool: ["cool", "cool-neutral"],
  neutral: ["warm", "cool", "warm-neutral", "cool-neutral"],
};

function fullFit(chip: MunsellChip, region: SeasonRegion): boolean {
  if (chip.value < region.vMin || chip.value > region.vMax) return false;
  if (chip.chroma < 3) return true;
  return tempOk(tempWeight(chip), region.kind) && chip.chroma >= region.cMin && chip.chroma <= region.cMax;
}

function tempCompat(chip: MunsellChip, region: SeasonRegion): boolean {
  if (chip.chroma < 3) return true;
  const w = tempWeight(chip);
  return region.kind === "warm" || region.kind === "warm-neutral" ? w >= -0.45 : w <= 0.45;
}

const seasonsCache = new Map<string, PersonalSeason[]>();

/**
 * The seasons a palette legally belongs to, by the region test. Replaces
 * the hand-written lists (removed in 1.3): membership is computed from
 * the palette's own colors, every time, from measured data.
 */
export function paletteSeasons(palette: Palette): PersonalSeason[] {
  const hit = seasonsCache.get(palette.id);
  if (hit) return hit;
  const dc = hexToMunsell(palette.colors.dominant.hex);
  const sc = hexToMunsell(palette.colors.secondary.hex);
  const ac = hexToMunsell(palette.colors.accent.hex);
  const spread =
    Math.max(dc.value, sc.value, ac.value) - Math.min(dc.value, sc.value, ac.value);
  const cwt = (chip: MunsellChip, role: number) => (role * Math.min(chip.chroma, 3)) / 3;
  const wSum = cwt(dc, 3) + cwt(sc, 2);
  const raw =
    wSum > 0 ? (tempWeightEff(dc) * cwt(dc, 3) + tempWeightEff(sc) * cwt(sc, 2)) / wSum : 0;
  const score = 0.7 * raw + 0.3 * (UND_SIGN[palette.undertone] ?? 0);
  const maxChroma = Math.max(dc.chroma, sc.chroma, ac.chroma);
  const out: PersonalSeason[] = [];
  (Object.keys(SEASON_REGIONS) as PersonalSeason[]).forEach((season) => {
    const region = SEASON_REGIONS[season];
    const { kind, vMin, vMax, cMin, cMax } = region;
    if (dc.chroma < 3) {
      if (dc.chroma <= 2 && sc.chroma <= 2 && ac.chroma <= 2) {
        // A faint chord: the dominant's value band + the palette's declared
        // temperature decide. Bright regions need real chroma somewhere.
        if (dc.value < vMin || dc.value > vMax) return;
        if (!(UND_KINDS[palette.undertone] ?? UND_KINDS.neutral).includes(kind)) return;
        if (cMin >= 8 && maxChroma < 6) return;
        out.push(season);
        return;
      }
      if (dc.value < vMin - 2.6 || dc.value > vMax + 1.2) return;
      if (!tempOk(score, kind)) return;
      const carrier = sc;
      if (carrier.chroma > cMax + 2) return;
      if (carrier.value < vMin - 1.2 || carrier.value > vMax + 2.6) return;
      if (cMin >= 8 && carrier.chroma < 6 && spread < 6) return;
      if ((season === "true-winter" || season === "bright-winter") && spread < 4.5) return;
      if ((season === "soft-summer" || season === "soft-autumn") && spread > 5.5) return;
      if (season.startsWith("light-") && !(carrier.value >= 5.2 || dc.value >= 5.8)) return;
      out.push(season);
      return;
    }
    if (fullFit(dc, region)) {
      if (tempCompat(sc, region)) out.push(season);
      return;
    }
    // Bridge: muted chromatic architecture (navy, denim) whose 30% carries
    // the season's temperature.
    if (dc.chroma <= 4.5 && dc.value >= vMin && dc.value <= vMax) {
      const w = tempWeight(dc);
      const warmSide = kind === "warm" || kind === "warm-neutral";
      if (warmSide ? w < -0.95 : w > 0.95) return;
      if (Math.abs(score) >= 0.15 && !tempOk(score, RELAX[kind])) return;
      if (sc.chroma > cMax + 3) return;
      if (cMin >= 8 && sc.chroma < 6) return;
      out.push(season);
    }
  });
  seasonsCache.set(palette.id, out);
  return out;
}

/** One color against one region — used by the Theory page's region cards. */
export function colorInRegion(hex: string, season: PersonalSeason): boolean {
  return fullFit(hexToMunsell(hex), SEASON_REGIONS[season]);
}
