type Lab = [number, number, number];

function rgbToLab(r: number, g: number, b: number): Lab {
  const f = (c: number) => (c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4));
  const R = f(r), G = f(g), B = f(b);
  const x = (R * 0.4124 + G * 0.3576 + B * 0.1805) / 0.95047;
  const y = R * 0.2126 + G * 0.7152 + B * 0.0722;
  const z = (R * 0.0193 + G * 0.1192 + B * 0.9505) / 1.08883;
  const gamma = (t: number) => (t > 0.008856 ? Math.cbrt(t) : 7.787 * t + 16 / 116);
  const fx = gamma(x), fy = gamma(y), fz = gamma(z);
  return [116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)];
}

export function hexToLab(hex: string): Lab {
  const n = parseInt(hex.replace("#", ""), 16);
  return rgbToLab(((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255);
}

/** CIE76 distance in Lab space. */
export function deltaE(a: string, b: string): number {
  const la = hexToLab(a), lb = hexToLab(b);
  return Math.hypot(la[0] - lb[0], la[1] - lb[1], la[2] - lb[2]);
}

const CHIP_LABS: Lab[] = CHIPS.map(([, , , hex]) =>
  rgbToLab(((hex >> 16) & 255) / 255, ((hex >> 8) & 255) / 255, (hex & 255) / 255),
);

const chipCache = new Map<string, MunsellChip>();

/** The nearest renotation chip to any hex — its Munsell hue/value/chroma. */
export function hexToMunsell(hex: string): MunsellChip {
  const key = hex.toLowerCase();
  const hit = chipCache.get(key);
  if (hit) return hit;
  const lab = hexToLab(hex);
  let best = 0;
  let bestDist = Infinity;
  for (let i = 0; i < CHIPS.length; i++) {
    const cl = CHIP_LABS[i] as Lab;
    const d = (lab[0] - cl[0]) ** 2 + (lab[1] - cl[1]) ** 2 + (lab[2] - cl[2]) ** 2;
    if (d < bestDist) {
      bestDist = d;
      best = i;
    }
  }
  const [hueIndex, value, chroma] = CHIPS[best] as [number, number, number, number];
  const chip = { hueIndex, value, chroma };
  chipCache.set(key, chip);
  return chip;
}

const HUE_FAMILIES = ["R", "YR", "Y", "GY", "G", "BG", "B", "PB", "P", "RP"] as const;

/**
 * Specimen-label notation for a hex, e.g. "5PB 3/8" (2.0's data voice).
 * Neutrals (chroma 0) read "N 5/" — a gray has no hue to name.
 */
export function munsellNotation(hex: string): string {
  const chip = hexToMunsell(hex);
  if (chip.chroma === 0) return `N ${chip.value}/`;
  const family = HUE_FAMILIES[Math.floor(chip.hueIndex / 4)] ?? "R";
  const step = ((chip.hueIndex % 4) + 1) * 2.5;
  const stepLabel = step % 1 === 0 ? step.toFixed(0) : step.toFixed(1);
  return `${stepLabel}${family} ${chip.value}/${chip.chroma}`;
}

/** Temperature weight by Munsell hue family (R, YR, Y, GY, G, BG, B, PB, P, RP). */
const TEMP_W = [0.7, 1.0, 0.9, 0.3, -0.2, -0.6, -0.8, -0.7, -0.3, 0.2];

function tempWeight(chip: MunsellChip): number {
  return chip.chroma < 3 ? 0 : (TEMP_W[Math.floor(chip.hueIndex / 4)] ?? 0);
}

function tempWeightEff(chip: MunsellChip): number {
  return (TEMP_W[Math.floor(chip.hueIndex / 4)] ?? 0) * (Math.min(chip.chroma, 6) / 6);
}

